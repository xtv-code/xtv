const catalogs: Record<Locale, Catalog> = { zh, en, ja, ko }

function readLocale(): Locale {
  const saved = localStorage.getItem('xtv.locale')
  if (saved === 'zh' || saved === 'en' || saved === 'ja' || saved === 'ko') return saved
  const lang = navigator.language.toLowerCase()
  if (lang.startsWith('ja')) return 'ja'
  if (lang.startsWith('ko')) return 'ko'
  if (lang.startsWith('en')) return 'en'
  return 'zh'
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const template = catalogs[locale][key]
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

type I18nValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: MessageKey, vars?: Record<string, string | number>) => string
}

let currentLocale: Locale = readLocale()

export function contentLocale() {
  return currentLocale
}

const I18nContext = createContext<I18nValue | null>(null)

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale)
  currentLocale = locale
  useEffect(() => {
    document.documentElement.lang = LOCALES.find((item) => item.id === locale)?.html || 'zh-CN'
  }, [locale])
  const setLocale = useCallback((next: Locale) => {
    currentLocale = next
    localStorage.setItem('xtv.locale', next)
    setLocaleState(next)
  }, [])
  const t = useCallback((key: MessageKey, vars?: Record<string, string | number>) => translate(locale, key, vars), [locale])
  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('LocaleProvider is missing')
  return value
}

export function LanguageSwitch() {
  const { locale, setLocale, t } = useI18n()
  return (
    <select className="lang-switch" aria-label={t('lang.label')} value={locale} onChange={(event) => setLocale(event.target.value as Locale)}>
      {LOCALES.map((item) => <option key={item.id} value={item.id}>{item.label}</option>)}
    </select>
  )
}
